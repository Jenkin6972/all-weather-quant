#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Portfolio backtest for semi-left deep rebound signals.

Uses signals generated by research_semileft_deep_rebound.py.
Rules are deliberately simple:
- Buy next open from the signal CSV.
- Take profit at +10% using daily high, with T+1 constraint.
- Stop loss when close <= -8%, sell next open.
- Time stop after 20 trading days, sell next open.
"""

from __future__ import annotations

import argparse
import pickle
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np
import pandas as pd

from research_semileft_deep_rebound import normalize_daily_frame, normalize_symbol


EPS = 1e-12
INITIAL_CAPITAL = 100_000_000.0
DEFAULT_SIGNAL_CSV = Path("/app/tdx_data/semileft_deep_rebound_research/semileft_deep_rebound_signals.csv")
DEFAULT_MARKET_CACHE = Path("/app/workspace/data_cache/market_data_main_board_2020-01-01_2025-12-31_hfq_200_c9e24d15a649.pkl")
DEFAULT_OUTPUT_DIR = Path("/app/tdx_data/semileft_deep_rebound_portfolio")
WINDOW_BARS = 42


@dataclass
class Config:
    name: str
    max_positions: int = 10
    max_daily_buy: int = 2
    position_cash: float = 1_000_000.0
    take_profit_pct: float = 0.10
    stop_loss_pct: float = 0.08
    max_holding_days: int = 20
    start_date: pd.Timestamp = pd.Timestamp("2020-01-01")
    end_date: pd.Timestamp = pd.Timestamp("2025-12-31")


@dataclass
class Position:
    symbol: str
    buy_date: pd.Timestamp
    buy_price: float
    shares: float
    signal_date: pd.Timestamp
    signal_type: str
    max_profit_pct: float = 0.0
    max_drawdown_pct: float = 0.0
    pending_sell_reason: str = ""
    pending_sell_price: float = 0.0


def pct(value: float) -> str:
    return f"{value * 100:.2f}%"


def load_market_cache(path: Path) -> Dict[str, pd.DataFrame]:
    with path.open("rb") as file:
        raw_market_data = pickle.load(file)

    market_data: Dict[str, pd.DataFrame] = {}
    for raw_symbol, raw_data in raw_market_data.items():
        if raw_data is None or raw_data.empty:
            continue
        symbol = normalize_symbol(raw_symbol)
        data = normalize_daily_frame(raw_data)
        if data.empty:
            continue
        data["prev_close"] = data["close"].shift(1)
        market_data[symbol] = data.set_index("date", drop=False)
    return market_data


def load_signals(path: Path) -> pd.DataFrame:
    data = pd.read_csv(path, dtype={"symbol": str})
    data["symbol"] = data["symbol"].map(normalize_symbol)
    for column in ["peak_date", "signal_date", "buy_date"]:
        data[column] = pd.to_datetime(data[column], errors="coerce").dt.normalize()
    numeric_columns = [
        "drawdown_from_peak",
        "days_from_peak_to_30pct",
        "days_from_peak_to_signal",
        "signal_body_pct",
        "signal_lower_shadow_pct",
        "signal_volume_ratio_20",
        "pre20_return",
        "pre20_down_ratio",
        "buy_price",
    ]
    for column in numeric_columns:
        data[column] = pd.to_numeric(data[column], errors="coerce")
    data["long_lower_shadow"] = data["long_lower_shadow"].astype(str).str.lower().isin(["true", "1"])
    data["big_bull_body"] = data["big_bull_body"].astype(str).str.lower().isin(["true", "1"])
    return data.dropna(subset=["symbol", "signal_date", "buy_date", "buy_price"]).copy()


def apply_filter(signals: pd.DataFrame, name: str) -> pd.DataFrame:
    data = signals.copy()
    if name == "all":
        mask = pd.Series(True, index=data.index)
    elif name == "both":
        mask = data["long_lower_shadow"] & data["big_bull_body"]
    elif name == "panic_down75":
        mask = data["pre20_down_ratio"] >= 0.75
    elif name == "panic_pre20_lt25":
        mask = data["pre20_return"] <= -0.25
    elif name == "panic_pre20_lt25_both":
        mask = (data["pre20_return"] <= -0.25) & data["long_lower_shadow"] & data["big_bull_body"]
    elif name == "shadow_7_10":
        mask = (data["signal_lower_shadow_pct"] >= 0.07) & (data["signal_lower_shadow_pct"] < 0.10)
    elif name == "deep50":
        mask = data["drawdown_from_peak"] <= -0.50
    elif name == "deep50_self_crowd_ge50":
        base_mask = data["drawdown_from_peak"] <= -0.50
        daily_count = data[base_mask].groupby("signal_date").size()
        mask = base_mask & (data["signal_date"].map(daily_count).fillna(0) >= 50)
    elif name == "deep50_all_crowd_ge200":
        daily_count = data.groupby("signal_date").size()
        mask = (data["drawdown_from_peak"] <= -0.50) & (data["signal_date"].map(daily_count).fillna(0) >= 200)
    elif name == "balanced":
        mask = (
            (data["pre20_return"] <= -0.15)
            & (data["pre20_down_ratio"] >= 0.65)
            & (data["signal_volume_ratio_20"] < 2.5)
            & (data["drawdown_from_peak"] <= -0.35)
        )
    elif name == "balanced_self_crowd_ge50":
        base_mask = (
            (data["pre20_return"] <= -0.15)
            & (data["pre20_down_ratio"] >= 0.65)
            & (data["signal_volume_ratio_20"] < 2.5)
            & (data["drawdown_from_peak"] <= -0.35)
        )
        daily_count = data[base_mask].groupby("signal_date").size()
        mask = base_mask & (data["signal_date"].map(daily_count).fillna(0) >= 50)
    elif name == "balanced_all_crowd_ge200":
        daily_count = data.groupby("signal_date").size()
        mask = (
            (data["pre20_return"] <= -0.15)
            & (data["pre20_down_ratio"] >= 0.65)
            & (data["signal_volume_ratio_20"] < 2.5)
            & (data["drawdown_from_peak"] <= -0.35)
            & (data["signal_date"].map(daily_count).fillna(0) >= 200)
        )
    else:
        raise ValueError(f"unknown filter: {name}")

    output = data[mask].copy()
    output["rank_score"] = (
        (-output["pre20_return"].fillna(0)).clip(0, 0.5) * 4.0
        + output["pre20_down_ratio"].fillna(0) * 2.0
        + output["long_lower_shadow"].astype(float) * 1.0
        + output["big_bull_body"].astype(float) * 1.0
        + (-output["drawdown_from_peak"].fillna(0)).clip(0, 0.8)
    )
    return output.sort_values(["buy_date", "rank_score", "symbol"], ascending=[True, False, True])


class PortfolioBacktest:
    def __init__(self, config: Config, signals: pd.DataFrame, market_data: Dict[str, pd.DataFrame]) -> None:
        self.config = config
        self.signals = signals[
            (signals["buy_date"] >= config.start_date) & (signals["buy_date"] <= config.end_date)
        ].copy()
        self.signals_by_date = {
            date: group.sort_values(["rank_score", "symbol"], ascending=[False, True]).copy()
            for date, group in self.signals.groupby("buy_date")
        }
        self.market_data = market_data
        self.cash = INITIAL_CAPITAL
        self.positions: Dict[str, Position] = {}
        self.pending_sells: Dict[str, str] = {}
        self.equity_rows: List[dict] = []
        self.position_rows: List[dict] = []
        self.trade_rows: List[dict] = []
        self.skip_rows: List[dict] = []
        self.calendar = self.build_calendar()

    def build_calendar(self) -> List[pd.Timestamp]:
        dates = set()
        for data in self.market_data.values():
            if not data.empty:
                dates.update(data.index.tolist())
        return sorted(date for date in dates if self.config.start_date <= date <= self.config.end_date)

    def get_row(self, symbol: str, date: pd.Timestamp) -> Optional[pd.Series]:
        data = self.market_data.get(symbol)
        if data is None or date not in data.index:
            return None
        return data.loc[date]

    def is_limit_down_open(self, row: pd.Series) -> bool:
        prev_close = float(row["prev_close"]) if pd.notna(row.get("prev_close")) else 0.0
        open_price = float(row["open"]) if pd.notna(row.get("open")) else 0.0
        return prev_close > EPS and open_price / prev_close - 1.0 <= -0.095 + EPS

    def holding_days(self, position: Position, date: pd.Timestamp) -> int:
        data = self.market_data.get(position.symbol)
        if data is None:
            return 0
        return int(((data.index >= position.buy_date) & (data.index <= date)).sum())

    def sell_position(self, date: pd.Timestamp, symbol: str, price: float, reason: str) -> None:
        position = self.positions.get(symbol)
        if position is None:
            return
        proceeds = position.shares * price
        pnl = price / position.buy_price - 1.0 if position.buy_price > EPS else 0.0
        self.cash += proceeds
        self.position_rows.append(
            {
                "symbol": symbol,
                "signal_date": position.signal_date,
                "buy_date": position.buy_date,
                "sell_date": date,
                "buy_price": position.buy_price,
                "sell_price": price,
                "total_pnl_pct": pnl,
                "holding_days": self.holding_days(position, date),
                "reason": reason,
                "signal_type": position.signal_type,
                "max_profit_pct": position.max_profit_pct,
                "max_drawdown_pct": position.max_drawdown_pct,
            }
        )
        self.trade_rows.append({"date": date, "symbol": symbol, "action": "SELL", "price": price, "reason": reason, "pnl": pnl})
        del self.positions[symbol]

    def execute_pending_sells(self, date: pd.Timestamp) -> None:
        next_pending = {}
        for symbol, reason in self.pending_sells.items():
            row = self.get_row(symbol, date)
            if row is None:
                next_pending[symbol] = reason
                continue
            if self.is_limit_down_open(row):
                next_pending[symbol] = reason
                self.skip_rows.append({"date": date, "symbol": symbol, "reason": "limit_down_open_sell_roll"})
                continue
            self.sell_position(date, symbol, float(row["open"]), reason)
        self.pending_sells = next_pending

    def execute_buys(self, date: pd.Timestamp) -> None:
        candidates = self.signals_by_date.get(date)
        if candidates is None or candidates.empty:
            return
        buy_count = 0
        for _, signal in candidates.iterrows():
            if buy_count >= self.config.max_daily_buy:
                break
            if len(self.positions) >= self.config.max_positions:
                break
            symbol = normalize_symbol(signal["symbol"])
            if symbol in self.positions:
                continue
            row = self.get_row(symbol, date)
            if row is None:
                continue
            open_price = float(row["open"])
            if open_price <= EPS:
                continue
            cash_to_use = min(self.config.position_cash, self.cash)
            if cash_to_use <= EPS:
                break
            shares = cash_to_use / open_price
            self.cash -= cash_to_use
            self.positions[symbol] = Position(
                symbol=symbol,
                buy_date=date,
                buy_price=open_price,
                shares=shares,
                signal_date=signal["signal_date"],
                signal_type=str(signal["signal_type"]),
            )
            buy_count += 1
            self.trade_rows.append({"date": date, "symbol": symbol, "action": "BUY", "price": open_price, "reason": "entry"})

    def evaluate_positions(self, date: pd.Timestamp) -> None:
        for symbol, position in list(self.positions.items()):
            if symbol in self.pending_sells:
                continue
            row = self.get_row(symbol, date)
            if row is None:
                continue
            high_return = float(row["high"]) / position.buy_price - 1.0
            low_return = float(row["low"]) / position.buy_price - 1.0
            close_return = float(row["close"]) / position.buy_price - 1.0
            position.max_profit_pct = max(position.max_profit_pct, high_return)
            position.max_drawdown_pct = min(position.max_drawdown_pct, low_return)

            holding_days = self.holding_days(position, date)
            if high_return >= self.config.take_profit_pct:
                if holding_days <= 1:
                    self.pending_sells[symbol] = "tp_t1_next_open"
                else:
                    self.sell_position(date, symbol, position.buy_price * (1.0 + self.config.take_profit_pct), "take_profit")
                continue
            if close_return <= -self.config.stop_loss_pct:
                self.pending_sells[symbol] = "stop_loss"
                continue
            if holding_days >= self.config.max_holding_days:
                self.pending_sells[symbol] = "time_stop"

    def mark_to_market(self, date: pd.Timestamp) -> None:
        total_value = self.cash
        invested_value = 0.0
        for symbol, position in self.positions.items():
            row = self.get_row(symbol, date)
            price = float(row["close"]) if row is not None else position.buy_price
            position_value = position.shares * price
            invested_value += position_value
            total_value += position_value
        self.equity_rows.append(
            {
                "date": date,
                "total_value": total_value,
                "cash": self.cash,
                "position_count": len(self.positions),
                "capital_utilization": invested_value / total_value if total_value > EPS else 0.0,
            }
        )

    def close_end_positions(self) -> None:
        if not self.calendar:
            return
        final_date = self.calendar[-1]
        for symbol in list(self.positions.keys()):
            row = self.get_row(symbol, final_date)
            if row is None:
                continue
            self.sell_position(final_date, symbol, float(row["close"]), "end_mark_to_market")

    def run(self) -> dict:
        for date in self.calendar:
            self.execute_pending_sells(date)
            self.execute_buys(date)
            self.evaluate_positions(date)
            self.mark_to_market(date)
        self.close_end_positions()
        return {
            "equity": pd.DataFrame(self.equity_rows),
            "positions": pd.DataFrame(self.position_rows),
            "trades": pd.DataFrame(self.trade_rows),
            "skips": pd.DataFrame(self.skip_rows),
        }


def equity_stats(equity: pd.DataFrame) -> dict:
    if equity.empty:
        return {}
    values = pd.to_numeric(equity["total_value"], errors="coerce").dropna().reset_index(drop=True)
    total_return = float(values.iloc[-1]) / INITIAL_CAPITAL - 1.0
    drawdown = values / values.cummax() - 1.0
    window_return = (values.shift(-WINDOW_BARS) / values - 1.0).dropna()
    return {
        "total_return": total_return,
        "annualized_return": (1.0 + total_return) ** (252.0 / len(values)) - 1.0,
        "max_drawdown": float(drawdown.min()),
        "win_42": float((window_return > 0).mean()),
        "avg_42": float(window_return.mean()),
        "median_42": float(window_return.median()),
        "min_42": float(window_return.min()),
        "avg_capital_utilization": float(equity["capital_utilization"].mean()),
        "max_position_count": int(equity["position_count"].max()),
    }


def position_stats(positions: pd.DataFrame) -> dict:
    if positions.empty:
        return {
            "trade_count": 0,
            "trade_win_rate": 0.0,
            "avg_trade_return": 0.0,
            "median_trade_return": 0.0,
            "avg_holding_days": 0.0,
            "profit_factor": 0.0,
        }
    returns = pd.to_numeric(positions["total_pnl_pct"], errors="coerce")
    wins = returns[returns > 0]
    losses = returns[returns <= 0]
    gross_loss = -float(losses.sum())
    return {
        "trade_count": int(len(positions)),
        "trade_win_rate": float((returns > 0).mean()),
        "avg_trade_return": float(returns.mean()),
        "median_trade_return": float(returns.median()),
        "avg_holding_days": float(positions["holding_days"].mean()),
        "profit_factor": float(wins.sum()) / gross_loss if gross_loss > 0 else 0.0,
    }


def render_row(row: dict) -> str:
    return (
        f"{row['name']:<24} sig={row['signal_count']:>5} "
        f"ann={pct(row['annualized_return']):>8} "
        f"mdd={pct(row['max_drawdown']):>8} "
        f"win42={pct(row['win_42']):>8} "
        f"avg42={pct(row['avg_42']):>8} "
        f"trades={row['trade_count']:>4} "
        f"tr_win={pct(row['trade_win_rate']):>8} "
        f"tr_avg={pct(row['avg_trade_return']):>8} "
        f"tr_med={pct(row['median_trade_return']):>8} "
        f"PF={row['profit_factor']:>5.2f} "
        f"hold={row['avg_holding_days']:>5.1f} "
        f"util={pct(row['avg_capital_utilization']):>8}"
    )


def run_variant(name: str, signals: pd.DataFrame, market_data: Dict[str, pd.DataFrame], args: argparse.Namespace) -> dict:
    filtered = apply_filter(signals, name)
    config = Config(
        name=name,
        max_positions=args.max_positions,
        max_daily_buy=args.max_daily_buy,
        position_cash=args.position_cash,
        take_profit_pct=args.take_profit_pct,
        stop_loss_pct=args.stop_loss_pct,
        max_holding_days=args.max_holding_days,
        start_date=pd.Timestamp(args.start),
        end_date=pd.Timestamp(args.end),
    )
    engine = PortfolioBacktest(config, filtered, market_data)
    result = engine.run()
    output_dir = Path(args.output_dir) / name
    output_dir.mkdir(parents=True, exist_ok=True)
    result["equity"].to_csv(output_dir / "equity.csv", index=False, encoding="utf-8-sig")
    result["positions"].to_csv(output_dir / "positions.csv", index=False, encoding="utf-8-sig")
    result["trades"].to_csv(output_dir / "trades.csv", index=False, encoding="utf-8-sig")
    result["skips"].to_csv(output_dir / "skips.csv", index=False, encoding="utf-8-sig")
    row = {"name": name, "signal_count": int(len(filtered))}
    row.update(equity_stats(result["equity"]))
    row.update(position_stats(result["positions"]))
    return row


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--signals-csv", default=str(DEFAULT_SIGNAL_CSV))
    parser.add_argument("--market-cache", default=str(DEFAULT_MARKET_CACHE))
    parser.add_argument("--output-dir", default=str(DEFAULT_OUTPUT_DIR))
    parser.add_argument("--start", default="2020-01-01")
    parser.add_argument("--end", default="2025-12-31")
    parser.add_argument("--max-positions", type=int, default=10)
    parser.add_argument("--max-daily-buy", type=int, default=2)
    parser.add_argument("--position-cash", type=float, default=1_000_000.0)
    parser.add_argument("--take-profit-pct", type=float, default=0.10)
    parser.add_argument("--stop-loss-pct", type=float, default=0.08)
    parser.add_argument("--max-holding-days", type=int, default=20)
    parser.add_argument("--variants", nargs="*", default=[
        "all",
        "both",
        "panic_down75",
        "panic_pre20_lt25",
        "panic_pre20_lt25_both",
        "shadow_7_10",
        "deep50",
        "balanced",
    ])
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    print("加载信号与行情缓存...", flush=True)
    signals = load_signals(Path(args.signals_csv))
    market_data = load_market_cache(Path(args.market_cache))
    rows = []
    for name in args.variants:
        print(f"RUN {name}", flush=True)
        rows.append(run_variant(name, signals, market_data, args))

    summary = pd.DataFrame(rows).sort_values(["annualized_return", "win_42", "avg_trade_return"], ascending=[False, False, False])
    summary.to_csv(output_dir / "summary.csv", index=False, encoding="utf-8-sig")
    lines = [
        "半左侧深跌反弹组合回测",
        "=" * 170,
        f"区间: {args.start} ~ {args.end}",
        f"退出: +{args.take_profit_pct*100:.1f}% 定价止盈 / -{args.stop_loss_pct*100:.1f}% 收盘止损次日开盘 / {args.max_holding_days}日时间止损",
        f"持仓: max_positions={args.max_positions}, max_daily_buy={args.max_daily_buy}, position_cash={args.position_cash:,.0f}",
        "",
    ]
    for _, row in summary.iterrows():
        lines.append(render_row(row.to_dict()))
    report = "\n".join(lines)
    (output_dir / "report.txt").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
